# extract.py
import pandas as pd
from sodapy import Socrata
from dotenv import load_dotenv
import os
from prefect import task

@task(retries=3, retry_delay_seconds=[10, 10, 10])
def extract_data():
    '''
    Extract incident data reported to the Cambridge Police Department
    using the Socrata Open Data API.
    Return the incident data as a Pandas DataFrame.
    '''
    load_dotenv()
    APP_TOKEN = os.getenv("SOCRATA_APP_TOKEN")

    client = Socrata(
        "data.cambridgema.gov",
        APP_TOKEN,
        timeout=30
    )

    DATASET_ID = "3gki-wyrb"
    results = client.get_all(DATASET_ID)

    results_df = pd.DataFrame.from_records(results)
    return results_df

# validate.py
import pandas as pd
from collections import Counter
from prefect import task

SCHEMA_COLS = [
    "date_time",
    "id",
    "type",
    "subtype",
    "location",
    "last_updated",
    "description"
]

def check_schema(df):
    # check if all expected columns are present
    if Counter(df.columns) != Counter(SCHEMA_COLS):
        raise ValueError("Schema does not match with the expected schema.")

def check_numeric_id(df):
    # convert id to numeric, non-numeric values become NaN
    df["id"] = pd.to_numeric(df["id"], errors="coerce")
    return df

def check_datetime_format(df):
    # validate datetimes follow ISO 8601 format
    try:
        pd.to_datetime(df["date_time"], format="ISO8601", errors="raise")
    except Exception:
        raise ValueError("Datetime does not follow ISO 8601 format.")

def check_missing_values(df):
    # check no missing values in required columns
    required_cols = ["date_time", "id", "type", "location"]
    if df[required_cols].isnull().any().any():
        df.dropna(subset=required_cols, inplace=True)

@task
def validate_data(df):
    df = df.copy()
    check_schema(df)
    df = check_numeric_id(df)
    check_missing_values(df)
    check_datetime_format(df)
    return df

# transform.py
import pandas as pd
from prefect import task

@task
def transform_data(df):
    df = df.copy()

    # remove rows with NaN id and duplicates
    df.dropna(subset=["id"], inplace=True)
    df.drop_duplicates(subset=["id"], inplace=True)
    df["id"] = df["id"].astype(int)

    # convert to datetime
    df["date_time"] = pd.to_datetime(df["date_time"])
    df["last_updated"] = pd.to_datetime(df["last_updated"])

    # extract year/month/day/time
    df["year"] = df["date_time"].dt.year
    df["month"] = df["date_time"].dt.month
    df["day"] = df["date_time"].dt.day
    df["hour"] = df["date_time"].dt.hour
    df["minute"] = df["date_time"].dt.minute
    df["second"] = df["date_time"].dt.second

    return df

# load.py
import os
from dotenv import load_dotenv
from sqlalchemy import create_engine, text
from prefect import task

@task
def load_data(df):
    load_dotenv()

    # For Docker PostgreSQL setup:
    # db_url = f"postgresql://{os.getenv('POSTGRES_USER')}:{os.getenv('POSTGRES_PASSWORD')}@localhost:5433/cpd_db"
    db_url = os.getenv("DATABASE_URL", "sqlite:///cpd_db.db")

    engine = create_engine(db_url)

    create_table_query = """
    CREATE TABLE IF NOT EXISTS cpd_incidents (
        date_time TIMESTAMP,
        id INTEGER PRIMARY KEY,
        type TEXT,
        subtype TEXT,
        location TEXT,
        description TEXT,
        last_updated TIMESTAMP,
        year INTEGER,
        month INTEGER,
        day INTEGER,
        hour INTEGER,
        minute INTEGER,
        second INTEGER
    );
    """

    with engine.begin() as conn:
        conn.execute(text(create_table_query))

    # load transformed dataframe into sql table
    df.to_sql("cpd_incidents", con=engine, if_exists="replace", index=False)
    print("Data loaded successfully. Total rows:", len(df))

# pipeline.py
from prefect import flow

@flow
def cpd_etl_pipeline():
    print("Extracting data...")
    extracted_df = extract_data()

    print("Validating data...")
    validated_df = validate_data(extracted_df)

    print("Performing data transformations...")
    transformed_df = transform_data(validated_df)

    print("Loading data into database...")
    load_data(transformed_df)

    return transformed_df

if __name__ == "__main__":
    final_df = cpd_etl_pipeline()
